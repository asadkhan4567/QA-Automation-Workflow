const ctx = $input.first().json;
const cfg = $('Config').first().json;
const key = ctx.ticket.key;
const branch = `qa/${key}`;
const dispatch_id = `${key}-${$execution.id}-${Date.now()}`;
const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
const matrix = [
  '| ID | Title | Priority | Type | Expected | Tags |',
  '|---|---|---|---|---|---|',
  ...ctx.design.test_matrix.map((r) => `| ${cell(r.id)} | ${cell(r.title)} | ${cell(r.priority)} | ${cell(r.type)} | ${cell(r.expected)} | ${cell((r.tags || []).join(' '))} |`),
].join('\n');
const verdict = ctx.review.verdict;
const issues = ctx.review.issues.length
  ? ctx.review.issues.map((i) => `- **${i.severity}** ${i.file ? '`' + i.file + (i.line ? ':' + i.line : '') + '`' : ''} ${i.problem}${i.fix ? ' → ' + i.fix : ''}`).join('\n')
  : '_none_';
const warn = verdict === 'CHANGES'
  ? `> [!WARNING]\n> Review gate still returned **CHANGES** after ${ctx.attempt} revision(s). Human attention required before this PR is used.\n\n`
  : '';
const body = `${warn}## ${key} — ${ctx.ticket.summary}\n\nJira: ${ctx.ticket.url}\nModule: \`@${ctx.design.module}\` · Grep: \`${ctx.spec.grep}\`\n\n` +
  `### Test matrix\n${matrix}\n\n` +
  `### Review verdict: \`${verdict}\` (revisions: ${ctx.attempt})\n${ctx.review.summary}\n\n${issues}\n\n` +
  `### Files\n${ctx.all_files.map((f) => '- `' + f.path + '`').join('\n')}\n\n` +
  (ctx.design.assumptions.length ? `### Assumptions\n${ctx.design.assumptions.map((a) => '- ' + a).join('\n')}\n\n` : '') +
  `---\nGenerated by n8n **QA | Design & Automate** (execution ${$execution.id}). Never auto-merged — a human approves and merges.`;
return [{
  json: {
    ...ctx,
    branch,
    dispatch_id,
    grep: ctx.spec.grep,
    commit_message: `test(${key}): add generated Playwright tests\n\nReview verdict: ${verdict}\nSource: n8n execution ${$execution.id}`,
    pr_title: `[QA] ${key}: automated tests — ${ctx.ticket.summary}`.slice(0, 250),
    pr_body: body,
    tree: ctx.all_files.map((f) => ({ path: f.path, mode: '100644', type: 'blob', content: f.content })),
    pr_draft: cfg.PR_DRAFT === true || cfg.PR_DRAFT === 'true',
  },
}];
